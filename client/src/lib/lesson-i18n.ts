/**
 * Retorna as strings de UI no idioma do professor selecionado.
 * Fallback: pt-BR se o idioma não tiver tradução.
 */
export function getLessonStrings(langCode: string): LessonUIStrings {
  // Tenta exato (ex: "en-GB")
  if (translations[langCode]) return translations[langCode];
  // Tenta prefixo (ex: "en" → "en-GB" ou "en-US")
  const prefix = langCode.split("-")[0].toLowerCase();
  const match = Object.keys(translations).find(k => k.toLowerCase().startsWith(prefix));
  if (match) return translations[match];
  // Fallback pt-BR
  return translations["pt-BR"];
}

/**
 * Retorna o código de idioma do professor selecionado atualmente.
 * Lê do localStorage: ml_selected_teacher_lang
 */
export function getSelectedTeacherLang(): string {
  return localStorage.getItem("ml_selected_teacher_lang") || 
         localStorage.getItem("ml_native_lang") || 
         "pt-BR";
}

/**
 * Salva o idioma do professor selecionado.
 */
export function setSelectedTeacherLang(langCode: string): void {
  localStorage.setItem("ml_selected_teacher_lang", langCode);
}

/**
 * Hook helper — retorna strings para o idioma atual do professor.
 */
export function useTeacherStrings(): LessonUIStrings {
  return getLessonStrings(getSelectedTeacherLang());
}
